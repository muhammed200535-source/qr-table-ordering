-- Masa Demo: Supabase kurulum betiği
-- DİKKAT: Politikalar demo için tamamen açıktır. Gerçek müşteri verisi koyma.

create table if not exists menu_items (
  id bigint generated by default as identity primary key,
  category text not null,
  name text not null, name_en text, name_bg text,
  description text, description_en text, description_bg text,
  price numeric(10,2) not null,
  emoji text default '🍽️',
  sold_out boolean not null default false,
  sort int not null default 0
);

create table if not exists orders (
  id bigint generated by default as identity primary key,
  table_no int not null,
  items jsonb not null,            -- [{id, name, price, qty}]
  note text,
  status text not null default 'new' check (status in ('new','prep','ready','served')),
  created_at timestamptz not null default now()
);

create table if not exists calls (
  id bigint generated by default as identity primary key,
  table_no int not null,
  kind text not null check (kind in ('waiter','bill')),
  method text check (method in ('cash','card')),
  created_at timestamptz not null default now()
);

create table if not exists payments (
  id bigint generated by default as identity primary key,
  table_no int not null,
  total numeric(10,2) not null,
  method text,
  items jsonb,
  created_at timestamptz not null default now()
);

-- Demo politikaları (herkes okuyup yazabilir)
do $$
declare t text;
begin
  foreach t in array array['menu_items','orders','calls','payments'] loop
    execute format('alter table %I enable row level security', t);
    execute format('create policy "demo_all" on %I for all to anon, authenticated using (true) with check (true)', t);
  end loop;
end $$;

-- Canlı güncelleme (realtime)
alter publication supabase_realtime add table menu_items, orders, calls, payments;

